"""Wiki integration: source-summary pages and topic page create/update."""

from __future__ import annotations

import re
from pathlib import Path

from scripts.config import Vault
from scripts.extractors.tools import fmt_time
from scripts.models import Analysis, SourceDoc
from scripts.storage import dump_frontmatter, parse_frontmatter, slugify

MAX_TOPICS = 5


def _bullets(items: list[str]) -> str:
    return "\n".join(f"- {i}" for i in items) if items else "- None identified."


def append_to_section(body: str, heading: str, line: str) -> str:
    """Append `line` to the end of `## heading`, creating the section if missing."""
    match = re.search(rf"^## {re.escape(heading)}[ \t]*$", body, re.MULTILINE)
    if not match:
        return f"{body.rstrip()}\n\n## {heading}\n\n{line}\n"
    end = match.end()
    nxt = re.search(r"^## ", body[end:], re.MULTILINE)
    stop = end + nxt.start() if nxt else len(body)
    block = body[end:stop].rstrip("\n")
    return f"{body[:end]}{block}\n{line}\n\n{body[stop:]}".rstrip("\n") + "\n"


def _review(review: list[str] | None, doc: SourceDoc) -> str:
    lines = (
        [f"- Pages: {doc.page_count}; page markers kept in the extraction."]
        if doc.page_count
        else []
    )
    if doc.media_kind:
        lines.append(
            f"- Transcribed locally with faster-whisper `{doc.extraction_model}` "
            f"(language: {doc.language or 'unknown'}, duration: {fmt_time(doc.duration_seconds)}); "
            "automatic speech recognition can mishear names, numbers and terms."
        )
        if doc.frames:
            lines.append(f"- {len(doc.frames)} frames sampled for visual context.")
    lines += [f"- Needs review: {r}" for r in review or []]
    return "".join(f"{line}\n" for line in lines)


def write_source_summary(
    vault: Vault,
    doc: SourceDoc,
    analysis: Analysis,
    slug: str,
    topic_slugs: list[str],
    processed_paths: list[str],
    provider_name: str,
    model: str,
    processed_at: str,
    review: list[str] | None = None,
) -> Path:
    meta, _ = parse_frontmatter((vault.root / "templates" / "source-summary.md").read_text("utf-8"))
    meta.update(
        title=doc.title,
        source_type=doc.source_type,
        source_url=doc.source_url,
        raw_path=doc.raw_path,
        processed_paths=processed_paths,
        creator=doc.author,
        captured_at=doc.captured_at,
        processed_at=processed_at,
        content_hash=doc.content_hash,
        privacy=doc.privacy,
        llm_provider=provider_name,
        llm_model=model,
        status="active",
        tags=[f"source/{doc.source_type}"],
    )
    extraction = ", ".join(f"`{p}`" for p in processed_paths)
    related = "\n".join(f"- [[topics/{t}]]" for t in topic_slugs) or "- None yet."
    body = f"""# {doc.title}

## Summary

{analysis.summary or "No summary produced."}

## Main ideas

{_bullets(analysis.main_ideas)}

## Important claims

{_bullets(analysis.claims)}

## Useful examples

- None extracted.

## Questions raised

{_bullets(analysis.questions)}

## Contradictions

- None recorded.

## Related wiki pages

{related}

## Processing notes

- Summary generated by `{provider_name}` / `{model}`; verify against the raw source.
- Extraction: {extraction} (reproducible, not LLM-written).
{_review(review, doc)}
## Provenance

- Original: {doc.source_url or doc.raw_path}
- Raw file: `{doc.raw_path}`
- SHA-256: `{doc.content_hash}`
- Captured: {doc.captured_at or "unknown"}
- Author: {doc.author or "unknown"}
- Privacy: {doc.privacy}
"""
    path = vault.root / "wiki" / "sources" / f"{slug}.md"
    path.write_text(dump_frontmatter(meta, body), encoding="utf-8")
    return path


def _claims_for(concept: str, claims: list[str]) -> list[str]:
    needle = concept.lower()
    return [c for c in claims if needle in c.lower()]


def integrate_topics(
    vault: Vault, doc: SourceDoc, analysis: Analysis, source_slug: str, today: str
) -> tuple[list[str], list[str]]:
    """Create or update `wiki/topics/<concept>.md`. Returns (created, updated) slugs."""
    template = (vault.root / "templates" / "topic.md").read_text("utf-8")
    topics_dir = vault.root / "wiki" / "topics"
    link = f"[[sources/{source_slug}]]"
    created: list[str] = []
    updated: list[str] = []
    seen: set[str] = set()

    for concept in analysis.concepts[:MAX_TOPICS]:
        slug = slugify(concept)
        if slug in seen:
            continue
        seen.add(slug)
        evidence = [f"- {c} {link}" for c in _claims_for(concept, analysis.claims)]
        evidence_text = "\n".join(evidence) or f"- Discussed in {link}."
        path = topics_dir / f"{slug}.md"

        if path.exists():
            meta, body = parse_frontmatter(path.read_text("utf-8"))
            if link in body or f"sources/{source_slug}" in (meta.get("sources") or []):
                continue  # already integrated: idempotent re-run
            for line in evidence_text.splitlines():
                body = append_to_section(body, "Evidence", line)
            body = append_to_section(body, "Sources", f"- {link}")
            meta["sources"] = [*(meta.get("sources") or []), f"sources/{source_slug}"]
            meta["updated"] = today
            path.write_text(dump_frontmatter(meta, body), encoding="utf-8")
            updated.append(slug)
        else:
            meta, body = parse_frontmatter(template)
            meta.update(
                title=concept,
                status="active",
                privacy=doc.privacy,
                created=today,
                updated=today,
                sources=[f"sources/{source_slug}"],
                tags=["topic"],
            )
            body = body.replace("# Topic", f"# {concept}", 1)
            body = append_to_section(body, "Overview", f"First seen in {link}.")
            body = append_to_section(body, "Evidence", evidence_text)
            body = append_to_section(body, "Sources", f"- {link}")
            path.write_text(dump_frontmatter(meta, body), encoding="utf-8")
            created.append(slug)

    return created, updated


def topic_slugs(analysis: Analysis) -> list[str]:
    out: list[str] = []
    for concept in analysis.concepts[:MAX_TOPICS]:
        slug = slugify(concept)
        if slug not in out:
            out.append(slug)
    return out


def write_book_page(
    vault: Vault,
    doc: SourceDoc,
    analysis: Analysis,
    source_slug: str,
    topic_slugs: list[str],
    processed_path: str,
    processed_at: str,
    today: str,
) -> Path:
    """Create `wiki/books/<title>.md`, or append this source to an existing one."""
    path = vault.root / "wiki" / "books" / f"{slugify(doc.title)}.md"
    link = f"[[sources/{source_slug}]]"
    if path.exists():
        meta, body = parse_frontmatter(path.read_text("utf-8"))
        if link in body:
            return path  # idempotent re-run
        body = append_to_section(body, "Sources", f"- {link}")
        meta["sources"] = [*(meta.get("sources") or []), f"sources/{source_slug}"]
        path.write_text(dump_frontmatter(meta, body), encoding="utf-8")
        return path

    meta, body = parse_frontmatter((vault.root / "templates" / "book.md").read_text("utf-8"))
    meta.update(
        title=doc.title,
        author=doc.author,
        status="reading",
        privacy=doc.privacy,
        source=doc.raw_path,
        processed_at=processed_at,
        sources=[f"sources/{source_slug}"],
    )
    body = body.replace("# Book title", f"# {doc.title}", 1)
    info_lines = [
        f"Pages: {doc.page_count}",
        f"Author: {doc.author or 'unknown'}",
        f"Raw file: `{doc.raw_path}`; extraction: `{processed_path}`",
    ]
    topics = _bullets([f"[[topics/{t}]]" for t in topic_slugs])
    sections = {
        "Bibliographic information": _bullets(info_lines),
        "Overview": f"{analysis.summary or 'No summary produced.'} {link}",
        "Key arguments": _bullets([f"{c} {link}" for c in analysis.claims]),
        "Concepts": topics,
        "Questions": _bullets(analysis.questions),
        "Related topics": topics,
        "Sources": f"- {link}",
    }
    for heading, text in sections.items():
        body = append_to_section(body, heading, text)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dump_frontmatter(meta, body), encoding="utf-8")
    return path


def write_video_page(
    vault: Vault,
    doc: SourceDoc,
    analysis: Analysis,
    source_slug: str,
    topic_slugs: list[str],
    processed_paths: list[str],
    uncertainty: list[str],
) -> Path:
    """Create `wiki/videos/<title>.md` from the video template, or append this source."""
    path = vault.root / "wiki" / "videos" / f"{slugify(doc.title)}.md"
    link = f"[[sources/{source_slug}]]"
    if path.exists():
        meta, body = parse_frontmatter(path.read_text("utf-8"))
        if link in body:
            return path  # idempotent re-run
        body = append_to_section(body, "Sources", f"- {link}")
        meta["sources"] = [*(meta.get("sources") or []), f"sources/{source_slug}"]
        path.write_text(dump_frontmatter(meta, body), encoding="utf-8")
        return path

    meta, body = parse_frontmatter((vault.root / "templates" / "video.md").read_text("utf-8"))
    meta.update(
        title=doc.title,
        creator=doc.author,
        source_url=doc.source_url,
        language=doc.language,
        transcript_kind="whisper",
        status="active",
        privacy=doc.privacy,
        sources=[f"sources/{source_slug}"],
    )
    body = body.replace("# Video title", f"# {doc.title}", 1)
    topics = _bullets([f"[[topics/{t}]]" for t in topic_slugs])
    sections = {
        "Summary": f"{analysis.summary or 'No summary produced.'} {link}",
        "Chapters and timestamps": (
            f"Not generated. Timestamps are in the transcript: `{processed_paths[0]}`."
        ),
        "Key claims": _bullets([f"{c} {link}" for c in analysis.claims]),
        "Concepts": topics,
        "Uncertainty": _bullets(["Transcript is automatic speech recognition.", *uncertainty]),
        "Related topics": topics,
        "Sources": f"- {link}",
    }
    for heading, text in sections.items():
        body = append_to_section(body, heading, text)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dump_frontmatter(meta, body), encoding="utf-8")
    return path
